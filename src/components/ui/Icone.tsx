export type NomIcone = keyof typeof ICONES;

export function Icone({ nom, ...props }: { nom: NomIcone } & LucideProps) {
  const Composant = ICONES[nom] ?? Info;
  return <Composant aria-hidden="true" strokeWidth={1.9} {...props} />;
}
